# 2. Profit by Region
region_profit = df.groupby("Region")["Profit"].sum()

print("\nPROFIT BY REGION")
display(region_profit.sort_values(ascending=False))

# 3. Loss-making Products
loss_products = df.groupby("Product Name")["Profit"].sum()

print("\nTOP 10 LOSS-MAKING PRODUCTS")
display(loss_products.sort_values().head(10))

# 4. Discount Analysis
