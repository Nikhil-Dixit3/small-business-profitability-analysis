import pandas as pd

df = pd.read_csv("Sample - Superstore.csv", encoding="latin1")

print("Dataset loaded successfully!")

display(df.head())

print("Rows and Columns:", df.shape)

print("\nColumn Names:")
print(df.columns.tolist())

print("\nDataset Information:")
df.info()

# DATA CLEANING

# Check missing values
print("Missing Values:")
print(df.isnull().sum())

# Check duplicate records
print("\nDuplicate Records:", df.duplicated().sum())

# Convert Order Date into datetime format
df["Order Date"] = pd.to_datetime(
    df["Order Date"],
    format="mixed"
)

# Check data types
print("\nData Types:")
print(df.dtypes)

print("\nData Cleaning Check Completed!")

# BUSINESS PERFORMANCE ANALYSIS

total_sales = df["Sales"].sum()

total_profit = df["Profit"].sum()

total_orders = df["Order ID"].nunique()

total_quantity = df["Quantity"].sum()

profit_margin = (total_profit / total_sales) * 100

print("===== BUSINESS PERFORMANCE =====")

print("Total Revenue: $", round(total_sales, 2))

print("Total Profit: $", round(total_profit, 2))

print("Total Orders:", total_orders)

print("Total Products Sold:", total_quantity)

print("Profit Margin:", round(profit_margin, 2), "%")

# PROFIT BY CATEGORY

category_profit = df.groupby("Category")["Profit"].sum()

print("Profit by Category:")

display(category_profit.sort_values(ascending=False))

# MONTHLY PROFIT ANALYSIS

df["Month"] = df["Order Date"].dt.to_period("M")

monthly_profit = df.groupby("Month")["Profit"].sum()

print("Monthly Profit:")

display(monthly_profit)

# PROFIT BY CATEGORY - BAR CHART

category_profit = df.groupby("Category")["Profit"].sum()

plt.figure(figsize=(9, 5))

sns.barplot(
    x=category_profit.index,
    y=category_profit.values
)

plt.title("Profit by Product Category")
plt.xlabel("Product Category")
plt.ylabel("Total Profit ($)")

plt.tight_layout()
plt.show()

# MONTHLY PROFIT TREND

monthly_data = df.groupby(
    df["Order Date"].dt.to_period("M")
)["Profit"].sum()

plt.figure(figsize=(14, 5))

plt.plot(
    monthly_data.index.astype(str),
    monthly_data.values,
    marker="o"
)

plt.title("Monthly Profit Trend")
plt.xlabel("Month")
plt.ylabel("Profit ($)")

plt.xticks(rotation=90)
plt.grid(True)

plt.tight_layout()
plt.show()

# SALES VS PROFIT

plt.figure(figsize=(9, 5))

sns.scatterplot(
    data=df,
    x="Sales",
    y="Profit",
    hue="Category"
)

plt.title("Sales vs Profit Analysis")
plt.xlabel("Sales ($)")
plt.ylabel("Profit ($)")

plt.axhline(0, linestyle="--")

plt.tight_layout()
plt.show()

# BUSINESS INSIGHTS ANALYSIS

# 1. Profit by Subcategory
subcategory_profit = df.groupby("Sub-Category")["Profit"].sum()

